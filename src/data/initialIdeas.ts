export function createNewIdea(
  order_num: number,
  name: string,
  description: string,
  feasibility: number,
  impact: number
): Idea {
  const f = Math.min(5, Math.max(1, Math.round(feasibility)));
  const i = Math.min(5, Math.max(1, Math.round(impact)));
  return {
    id: `local-${Date.now()}-${Math.random().toString(36).substring(2, 8)}`,
    order_num,
    name,
    description,
    feasibility: f,
    impact: i,
    total_score: calculateTotalScore(f, i),
    quadrant: calculateQuadrant(f, i),
    created_at: new Date().toISOString(),
  };
}
